@tf.function
def deep_dream(img, steps=10, step_size=0.01):
    for i in range(steps):
        with tf.GradientTape() as tape:
            tape.watch(img)
            loss = tf.reduce_mean(dream_model(img))
        grads = tape.gradient(loss, img)
        grads /= tf.math.reduce_std(grads) + 1e-8
        img += grads * step_size
    return img

