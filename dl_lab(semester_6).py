# Implement Transformer model

import tensorflow as tf
from tensorflow.keras.layers import Input, Embedding, Dense, LayerNormalization, Dropout
from tensorflow.keras.models import Model

import numpy as np

def positional_encoding(max_len, d_model):
    pos = np.arange(max_len)[:, np.newaxis]
    i = np.arange(d_model)[np.newaxis, :]

    angles = pos / np.power(10000, (2*(i//2))/d_model)

    angles[:, 0::2] = np.sin(angles[:, 0::2])
    angles[:, 1::2] = np.cos(angles[:, 1::2])

    return tf.cast(angles, dtype=tf.float32)

from tensorflow.keras.layers import MultiHeadAttention

def transformer_block(x, d_model, num_heads, ff_dim):
    # Self-attention
    attn = MultiHeadAttention(num_heads=num_heads, key_dim=d_model)(x, x)
    x = LayerNormalization()(x + attn)

    # Feed Forward
    ffn = Dense(ff_dim, activation='relu')(x)
    ffn = Dense(d_model)(ffn)

    x = LayerNormalization()(x + ffn)
    return x

def build_transformer(vocab_size, max_len):

    d_model = 64
    num_heads = 2
    ff_dim = 128

    inputs = Input(shape=(max_len,))

    # Embedding + Position
    x = Embedding(vocab_size, d_model)(inputs)
    x = x + positional_encoding(max_len, d_model)

    # Transformer block
    x = transformer_block(x, d_model, num_heads, ff_dim)

    # Output
    outputs = Dense(vocab_size, activation='softmax')(x)

    model = Model(inputs, outputs)
    return model

