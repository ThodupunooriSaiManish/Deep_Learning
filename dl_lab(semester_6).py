import tensorflow as tf
from tensorflow.keras import layers, models
import numpy as np

# ------------------------------
# Load and preprocess MNIST
# ------------------------------
(X_train, y_train), (X_test, y_test) = tf.keras.datasets.mnist.load_data()

# Normalize
X_train = X_train / 255.0
X_test = X_test / 255.0

# Add channel dimension
X_train = X_train[..., tf.newaxis]
X_test = X_test[..., tf.newaxis]

# Resize to 32x32 (better for ViT)
X_train = tf.image.resize(X_train, (32, 32))
X_test = tf.image.resize(X_test, (32, 32))

# ------------------------------
# Parameters
# ------------------------------
input_shape = (32, 32, 1)
patch_size = 4
num_patches = (32 // patch_size) ** 2
projection_dim = 64
num_heads = 4
transformer_layers = 2
num_classes = 10

# ------------------------------
# Patch Extraction Layer
# ------------------------------
class Patches(layers.Layer):
    def __init__(self, patch_size):
        super().__init__()
        self.patch_size = patch_size

    def call(self, images):
        batch_size = tf.shape(images)[0]

        patches = tf.image.extract_patches(
            images=images,
            sizes=[1, self.patch_size, self.patch_size, 1],
            strides=[1, self.patch_size, self.patch_size, 1],
            rates=[1, 1, 1, 1],
            padding='VALID'
        )

        patch_dim = patches.shape[-1]
        patches = tf.reshape(patches, [batch_size, -1, patch_dim])
        return patches

# ------------------------------
# Patch Encoding Layer
# ------------------------------
class PatchEncoder(layers.Layer):
    def __init__(self, num_patches, projection_dim):
        super().__init__()
        self.projection = layers.Dense(projection_dim)
        self.position_embedding = layers.Embedding(
            input_dim=num_patches, output_dim=projection_dim
        )

    def call(self, patches):
        positions = tf.range(start=0, limit=num_patches, delta=1)
        encoded = self.projection(patches) + self.position_embedding(positions)
        return encoded

# ------------------------------
# Transformer Block
# ------------------------------
def transformer_block(x):
    # Layer Norm + Attention
    x1 = layers.LayerNormalization()(x)
    attention_output = layers.MultiHeadAttention(
        num_heads=num_heads, key_dim=projection_dim
    )(x1, x1)

    x2 = layers.Add()([x, attention_output])

    # Feed Forward
    x3 = layers.LayerNormalization()(x2)
    x3 = layers.Dense(projection_dim * 2, activation="relu")(x3)
    x3 = layers.Dense(projection_dim)(x3)

    return layers.Add()([x2, x3])

# ------------------------------
# Build ViT Model
# ------------------------------
inputs = layers.Input(shape=input_shape)

# Create patches
patches = Patches(patch_size)(inputs)

# Encode patches
encoded_patches = PatchEncoder(num_patches, projection_dim)(patches)

# Transformer layers
for _ in range(transformer_layers):
    encoded_patches = transformer_block(encoded_patches)

# Classification head
x = layers.LayerNormalization()(encoded_patches)
x = layers.Flatten()(x)
x = layers.Dense(64, activation="relu")(x)
outputs = layers.Dense(num_classes, activation="softmax")(x)

model = models.Model(inputs=inputs, outputs=outputs)

# ------------------------------
# Compile Model
# ------------------------------
model.compile(
    optimizer="adam",
    loss="sparse_categorical_crossentropy",
    metrics=["accuracy"]
)

model.summary()

# ------------------------------
# Train Model
# ------------------------------
model.fit(
    X_train, y_train,
    validation_data=(X_test, y_test),
    epochs=5,
    batch_size=64
)

