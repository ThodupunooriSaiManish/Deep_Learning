# Custom Contractive Layer
class ContractiveDense(Layer):
    def __init__(self, units, activation=None, lambda_reg=1e-4, **kwargs):
        super(ContractiveDense, self).__init__(**kwargs)
        self.units = units
        self.activation = tf.keras.activations.get(activation)
        self.lambda_reg = lambda_reg

    def build(self, input_shape):
        self.kernel = self.add_weight(
            name='kernel',
            shape=(input_shape[-1], self.units),
            initializer='glorot_uniform',
            trainable=True
        )
        self.bias = self.add_weight(
            name='bias',
            shape=(self.units,),
            initializer='zeros',
            trainable=True
        )
        super(ContractiveDense, self).build(input_shape)

    def call(self, inputs):
        z = tf.matmul(inputs, self.kernel) + self.bias

        h = self.activation(z) if self.activation is not None else z

        if self.activation == tf.keras.activations.sigmoid:
            h_prime_squared = tf.square(h * (1 - h))
        elif self.activation == tf.keras.activations.relu:
            h_prime_squared = tf.square(tf.cast(z > 0, dtype=tf.float32))
        else:

            h_prime_squared = tf.ones_like(h)

        sum_h_prime_squared_per_sample = tf.reduce_sum(h_prime_squared, axis=-1) # (batch_size,)

        frobenius_norm_squared_W = tf.reduce_sum(tf.square(self.kernel)) # scalar


        contractive_penalty = sum_h_prime_squared_per_sample * frobenius_norm_squared_W

        self.add_loss(self.lambda_reg * tf.reduce_mean(contractive_penalty))

        return h

    def compute_output_shape(self, input_shape):
        return (input_shape[0], self.units)

input_img = Input(shape=(784,))

encoded = ContractiveDense(128, activation='sigmoid', name='encoder_hidden_1')(input_img)
encoded = ContractiveDense(64, activation='sigmoid', name='encoder_hidden_2')(encoded) # Another contractive layer

decoded = Dense(128, activation='sigmoid', name='decoder_hidden_1')(encoded)
decoded = Dense(784, activation='sigmoid', name='decoder_output')(decoded)

contractive_ae = Model(input_img, decoded)

